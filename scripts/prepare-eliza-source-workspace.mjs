#!/usr/bin/env node
import { execFile } from "node:child_process";
import { cp, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);

function usage(exitCode = 0) {
  const out = exitCode === 0 ? console.log : console.error;
  out(`Usage:
  node scripts/prepare-eliza-source-workspace.mjs --target <dir> [--force]

Creates a migration workspace outside eliza-plugin/:
  source/                   recovered historical TypeScript source baseline
  current-dist/             current mirrored dist artifact reference
  migration-inventory.json  CI-protected source/dist/V5-V6 inventory
  README.md                 local migration notes`);
  process.exit(exitCode);
}

const args = process.argv.slice(2);
const force = args.includes("--force");
const targetIndex = args.indexOf("--target");
const target = targetIndex === -1 ? null : args[targetIndex + 1];

if (args.includes("--help") || args.includes("-h")) usage(0);
if (!target || target.startsWith("--")) usage(1);

const outDir = resolve(target);
try {
  const entries = await readdir(outDir);
  if (entries.length > 0 && !force) {
    console.error(`Refusing to write into non-empty target: ${outDir}`);
    console.error("Pass --force to remove and recreate that exact directory.");
    process.exit(1);
  }
  if (entries.length > 0) await rm(outDir, { recursive: true, force: true });
} catch (error) {
  if (error?.code !== "ENOENT") throw error;
}

await mkdir(outDir, { recursive: true });
const sourceDir = join(outDir, "source");
const distDir = join(outDir, "current-dist");

await execFileAsync(process.execPath, [
  "scripts/extract-eliza-source-baseline.mjs",
  "--target",
  sourceDir,
]);
await cp("eliza-plugin/dist", distDir, { recursive: true });

const { stdout: inventoryJson } = await execFileAsync(process.execPath, [
  "scripts/inventory-eliza-migration.mjs",
  "--json",
]);
await writeFile(join(outDir, "migration-inventory.json"), inventoryJson);

const inventory = JSON.parse(inventoryJson);
await writeFile(
  join(outDir, "README.md"),
  `# Eliza source migration workspace

This directory was generated by \`scripts/prepare-eliza-source-workspace.mjs\`.
It is a scratch workspace for the V7 migration and is not itself a publishable
package.

## Contents

- \`source/\` - recovered historical TypeScript source baseline.
- \`current-dist/\` - current mirrored artifact reference from \`eliza-plugin/dist\`.
- \`migration-inventory.json\` - generated comparison inventory.

## Current inventory

- Historical source files: ${inventory.baselineSourceFiles}
- Current dist files: ${inventory.currentDistFiles}
- Dist entries without historical source counterpart: ${inventory.currentDistWithoutBaselineSource.length}
- V5/V6 receipt migration hits: ${inventory.receiptMigrationHits.length}

## Immediate source work

1. Forward-port the current artifact-only \`merchant-card\` action into source.
2. Migrate \`intel-trust\`, \`verify-receipt\`, \`index\`, and registration tests
   from V5/V6 receipt wording and fixtures to V7 behavior.
3. Keep V6 verification as a downgraded legacy path where supported.
4. Build, test, publish \`@wzrd_sol/eliza-plugin\`, then resync this public mirror
   from the published artifact.
`,
);

await readFile(join(sourceDir, "src/actions/intel-trust.ts"), "utf8");
await readFile(join(distDir, "actions/merchant-card.js"), "utf8");

console.log(`Prepared Eliza source migration workspace at ${outDir}`);
