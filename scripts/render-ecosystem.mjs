#!/usr/bin/env node
// Renders the shared "TWZRD at a glance" block from docs/ecosystem.json and keeps every
// copy of it identical.
//   node scripts/render-ecosystem.mjs --print     print the block
//   node scripts/render-ecosystem.mjs --write     rewrite the block between the markers in TARGETS
//   node scripts/render-ecosystem.mjs --check     exit 1 if any copy differs from the render
// Other repos embed the same block between the same markers; to compare a copy with the source:
//   curl -s https://raw.githubusercontent.com/twzrd-sol/twzrd-trust/main/docs/ecosystem.json  (render it here)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const BEGIN = "<!-- twzrd:ecosystem:begin (generated by scripts/render-ecosystem.mjs from docs/ecosystem.json; edit that file) -->";
const END = "<!-- twzrd:ecosystem:end -->";
const TARGETS = ["docs/ECOSYSTEM.md", "README.md"];
const cell = (s) => s.replace(/\|/g, "\\|");

export function render(eco) {
  const out = [];
  out.push(`**${eco.tagline}**`, "");
  out.push("| You are | Free | Paid |", "|---|---|---|");
  for (const l of eco.lanes) out.push(`| ${cell(l.you_are)} | ${cell(l.free)} | ${cell(l.paid)} |`);
  out.push("", "Each piece below works alone. Plugged into the hosted checks, they form one pre-spend path.", "");
  out.push("| Piece | On its own | Plugged in | Install |", "|---|---|---|---|");
  for (const p of eco.pieces) {
    const name = p.link && !p.name.startsWith("[") ? `[${p.name}](${p.link})` : p.name;
    out.push(`| ${cell(name)} | ${cell(p.alone)} | ${cell(p.plugged_in)} | ${cell(p.install)} |`);
  }
  out.push("", "**Put them together**", "");
  for (const r of eco.recipes) out.push(`- **${r.title}:** ${r.uses}. ${r.result}`);
  out.push("", "**What TWZRD does not claim**", "");
  for (const s of eco.limits) out.push(`- ${s}`);
  return out.join("\n");
}

function loadEco() {
  return JSON.parse(readFileSync(join(root, "docs/ecosystem.json"), "utf8"));
}
function extract(text) {
  const i = text.indexOf(BEGIN), j = text.indexOf(END);
  if (i < 0 || j < 0 || j < i) return null;
  return { before: text.slice(0, i), body: text.slice(i + BEGIN.length, j), after: text.slice(j) };
}
const wrap = (block) => `\n${block}\n`;

const mode = process.argv[2] ?? "--check";
const block = render(loadEco());
if (mode === "--print") {
  console.log(block);
} else if (mode === "--write") {
  for (const t of TARGETS) {
    const p = join(root, t);
    const x = extract(readFileSync(p, "utf8"));
    if (!x) { console.error(`${t}: markers missing`); process.exit(1); }
    writeFileSync(p, x.before + BEGIN + wrap(block) + x.after);
    console.log(`${t}: written`);
  }
} else if (mode === "--check") {
  let bad = 0;
  for (const t of TARGETS) {
    const x = extract(readFileSync(join(root, t), "utf8"));
    if (!x) { console.error(`${t}: markers missing`); bad++; continue; }
    if (x.body !== wrap(block)) { console.error(`${t}: block differs from docs/ecosystem.json (run: node scripts/render-ecosystem.mjs --write)`); bad++; }
  }
  if (bad) process.exit(1);
  console.log("ecosystem blocks match docs/ecosystem.json");
} else {
  console.error("usage: render-ecosystem.mjs [--print|--write|--check]");
  process.exit(2);
}
